def main(prefix):
    out = ROOT/'assets/textbook'
    out.mkdir(parents=True,exist_ok=True)
    manifest=[]
    pages={i:Image.open(f'{prefix}-{i}.png').convert('RGB') for i in range(1,7)}
    for ident,page,bounds,title,section,width in SLICES:
        im=pages[page]
        box=tuple(round(v*(im.width/1061 if j%2==0 else im.height/1500)) for j,v in enumerate(bounds))
        crop=im.crop(box)
        path=out/f'{ident}.png'
        crop.save(path,optimize=True)
        manifest.append(dict(id=ident,path=f'./assets/textbook/{ident}.png',pdfPage=page,printedPage=33+page,title=title,section=section,pageId=f'{section}--{ident}' if section!='cover' else 'title',sourceBounds=box,referenceBounds=bounds,width=crop.width,height=crop.height,displayWidth=width,sha256=hashlib.sha256(path.read_bytes()).hexdigest()))
    for item in manifest:
        item['pageIds']=[item['pageId']]
        if item['id']=='an-process': item['pageIds'].append('an-impact--an-process')
        if item['id']=='five': item['pageIds'].append('tang-end--five')
    doc={'source':'中外历史纲要上_PDF第41-46页.pdf','sourceSha256':hashlib.sha256((ROOT/'中外历史纲要上_PDF第41-46页.pdf').read_bytes()).hexdigest(),'coordinateSystem':'top-left pixels on 3000px-high Poppler renders; measured from inspected 1061x1500 reference','slices':manifest}
    (out/'manifest.json').write_text(json.dumps(doc,ensure_ascii=False,indent=2),encoding='utf-8')
    (ROOT/'js/textbook-assets.js').write_text('/* Generated by tools/prepare_textbook.py; classic script for file://. */\nwindow.TEXTBOOK_ASSETS = '+json.dumps({m['id']:m for m in manifest},ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
    print(f'Generated {len(manifest)} crops')

if __name__=='__main__': main(sys.argv[1])
